/* ─────────────────────────────────────────────────────────────────
   APPLY LANGUAGE
   ───────────────────────────────────────────────────────────────── */
const langMeta = {
  id: { flag: "🇮🇩", code: "ID", htmlLang: "id" },
  en: { flag: "🇬🇧", code: "EN", htmlLang: "en" },
  fr: { flag: "🇫🇷", code: "FR", htmlLang: "fr" },
};

function applyLang(lang) {
  const dict = translations[lang];
  if (!dict) return;

  // Text content
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] !== undefined) el.textContent = dict[key];
  });

  // Placeholders
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (dict[key] !== undefined) el.setAttribute("placeholder", dict[key]);
  });

  // Update html lang attr
  document.documentElement.lang = langMeta[lang].htmlLang;

  // Update switcher button
  document.getElementById("langFlag").textContent = langMeta[lang].flag;
  document.getElementById("langCode").textContent  = langMeta[lang].code;

  // Persist
  localStorage.setItem("portfolio-lang", lang);

  // Animate page text swap
  document.body.style.transition = "opacity 0.18s ease";
  document.body.style.opacity = "0.85";
  setTimeout(() => { document.body.style.opacity = "1"; }, 180);
}

/* ─────────────────────────────────────────────────────────────────
   LANGUAGE SWITCHER UI
   ───────────────────────────────────────────────────────────────── */
const langBtn      = document.getElementById("langBtn");
const langDropdown = document.getElementById("langDropdown");

langBtn.addEventListener("click", (e) => {
  e.stopPropagation();
  langDropdown.classList.toggle("open");
  langBtn.querySelector(".lang-arrow").textContent =
    langDropdown.classList.contains("open") ? "expand_less" : "expand_more";
});

document.addEventListener("click", () => {
  langDropdown.classList.remove("open");
  langBtn.querySelector(".lang-arrow").textContent = "expand_more";
});

document.querySelectorAll(".lang-option").forEach((btn) => {
  btn.addEventListener("click", (e) => {
    e.stopPropagation();
    applyLang(btn.dataset.lang);
    langDropdown.classList.remove("open");
    langBtn.querySelector(".lang-arrow").textContent = "expand_more";
  });
});

